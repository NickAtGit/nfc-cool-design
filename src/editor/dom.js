export function icon(name) {
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('fill', 'none');
  svg.setAttribute('stroke', 'currentColor');
  svg.setAttribute('stroke-width', '2');
  svg.setAttribute('stroke-linecap', 'round');
  svg.setAttribute('stroke-linejoin', 'round');
  svg.setAttribute('aria-hidden', 'true');
  svg.innerHTML = GLYPHS[name];
  return svg;
}

/* One polite live region per page, shared by every part that speaks. */
let live;
export function announce(text) {
  if (!live || !live.isConnected) {
    live = h('div', { class: 'sr-only', 'aria-live': 'polite', 'aria-atomic': 'true', dataset: { edLive: '' } });
    document.body.append(live);
  }
  /* Cleared first, or the same sentence twice in a row is not read again. */
  live.textContent = '';
  requestAnimationFrame(() => { live.textContent = text; });
}
