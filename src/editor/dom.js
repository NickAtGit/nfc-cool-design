/* The small DOM vocabulary every part is written in. */

let counter = 0;
export const uid = (prefix = 'ed') => `${prefix}-${++counter}`;

/* h('button', { class: 'a b', type: 'button', onclick: fn }, 'text', child) */
export function h(tag, attrs, ...children) {
  const node = document.createElement(tag);
  for (const [key, value] of Object.entries(attrs || {})) {
    if (value === null || value === undefined || value === false) continue;
    if (key === 'class') { const c = String(value).trim(); if (c) node.className = c; }
    else if (key === 'dataset') Object.assign(node.dataset, value);
    else if (key.startsWith('on') && typeof value === 'function') node.addEventListener(key.slice(2), value);
    else if (key === 'value') node.value = value;
    else if (key === 'checked' || key === 'disabled' || key === 'hidden' || key === 'open' || key === 'multiple' || key === 'required' || key === 'readOnly') node[key] = true;
    else node.setAttribute(key, value === true ? '' : value);
  }
  append(node, children);
  return node;
}

export function append(node, children) {
  for (const child of children.flat(Infinity)) {
    if (child === null || child === undefined || child === false) continue;
    node.append(child.nodeType ? child : document.createTextNode(String(child)));
  }
  return node;
}

