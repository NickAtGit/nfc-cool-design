/* Writes dist/shell/django/: the page shell of build/emit-shell-swift.mjs as
   Django includes, from the same src/shell.js renders, for a consumer with no
   Node (business_card_service). Usage: node build/emit-shell-django.mjs.

   The variables are the Swift placeholders' names; Django's autoescape does
   the escaping. The two raw slots become includes of a template the caller
   names, because a Django include cannot take a block:

     {% include "nfccool_shell/side_nav.html" with label="Your team" brand_href="/org/" asset_base=logo_base
        theme_toggle_label="Toggle light or dark theme" menu_label="Menu" theme_group_label="Colour theme"
        theme_light="Light" theme_dark="Dark" privacy_label="Privacy" privacy_href="…" terms_label="Terms" terms_href="…"
        destinations_template="organization/dashboard/_nav_links.html"
        account_template="nfccool_shell/nav_account_link.html" %}

   where _nav_links.html includes nav_link.html / nav_link_current.html once
   per destination (`with href=… label=… icon=…`, icon being trusted path
   markup), and the account include reads initial, name, email, account_href,
   sign_out_action, sign_out_label and sign_out_confirm from the context. Its
   sign-out form carries {% csrf_token %}. */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { root } from './guideline.mjs';
import { shellRenders, swap } from './emit-shell-swift.mjs';

const out = join(root, 'dist/shell/django');
mkdirSync(out, { recursive: true });

const S = k => `ZZ${k}ZZ`;
const v = name => `{{ ${name} }}`;
const BANNER = '{% comment %}GENERATED by build/emit-shell-django.mjs from src/shell.js. Do not edit; rebuild the design package.{% endcomment %}\n';

const account = [
  [S('INITIAL'), v('initial')], [S('NAME'), v('name')], [S('OUT_ACTION'), v('sign_out_action')],
  [S('OUT_LABEL'), v('sign_out_label')], [S('OUT_CONFIRM'), v('sign_out_confirm')], [S('OUT_FIELDS'), '{% csrf_token %}'],
];
const link = [[S('HREF'), v('href')], [S('LABEL'), v('label')], [S('ICON'), '{{ icon|safe }}']];
const PLACEHOLDERS = {
  side_nav: [
    [S('DESTINATIONS'), '{% include destinations_template %}'], [S('ACCOUNT'), '{% include account_template %}'],
    [S('LABEL'), v('label')], [S('BRAND'), v('brand_href')], [S('ASSETS'), v('asset_base')],
    [S('TOGGLE'), v('theme_toggle_label')], [S('MENU'), v('menu_label')], [S('GROUP'), v('theme_group_label')],
    [S('LIGHT'), v('theme_light')], [S('DARK'), v('theme_dark')],
    [S('PRIVACY_HREF'), v('privacy_href')], [S('PRIVACY'), v('privacy_label')],
    [S('TERMS_HREF'), v('terms_href')], [S('TERMS'), v('terms_label')],
  ],
  nav_link: link,
  nav_link_current: link,
  nav_account: account,
  nav_account_link: [[S('ACCOUNT_HREF'), v('account_href')], [S('EMAIL'), v('email')], ...account],
  plain_header: [[S('BRAND'), v('brand_href')], [S('ASSETS'), v('asset_base')], [S('TOGGLE'), v('theme_toggle_label')]],
};

const renders = shellRenders();
for (const [name, html] of Object.entries(renders)) {
  const body = swap(html, PLACEHOLDERS[name]);
  if (/ZZ[A-Z_]+ZZ/.test(body)) throw new Error(`${name}: a sentinel survived`);
  writeFileSync(join(out, `${name}.html`), BANNER + body);
}
console.log(`wrote dist/shell/django/ (${Object.keys(renders).length} templates)`);
