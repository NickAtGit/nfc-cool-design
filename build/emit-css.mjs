/* Generates src/tokens.css (L1) and src/brands/<brand>.css (L2) from src/tokens.json.
   Run: node build/emit-css.mjs        Check only: node build/emit-css.mjs --check */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const t = JSON.parse(readFileSync(join(root, 'src/tokens.json'), 'utf8'));
const check = process.argv.includes('--check');
const BANNER = '/* GENERATED by build/emit-css.mjs from src/tokens.json. Do not edit. */\n';

const skip = k => k.startsWith('$');
const block = (obj, prefix) => Object.entries(obj).filter(([k]) => !skip(k))
  .map(([k, v]) => `   --${prefix}${k}: ${v};`).join('\n');

/* ---- L1 primitives ---- */
const p = t.primitives;
let l1 = BANNER + `/* Layer 1: primitives. Brand-neutral. No colour, no typeface.
   Derived from nfc-cool-website's own CSS. */

:root {
   /* Space - 4px grid, keeping 1.25rem as the signature grid gap */
${block(p.space, 'space-')}

   /* Section rhythm */
${block(p.section, 'section-')}

   /* Type ramp */
${block(p.text, 'text-')}

   /* Leading */
${block(p.leading, 'leading-')}

   /* Tracking - negative on display, positive on uppercase micro-labels */
${block(p.tracking, 'tracking-')}

   /* Measures */
${block(p.measure, 'measure-')}
   --container-padding: var(--measure-gutter);
   --max-width: var(--measure-max);
   --content-width: var(--measure-content);
   --prose-width: var(--measure-prose);
   --faq-width: var(--measure-faq);
   --hero-media-width: var(--measure-hero-media);
   --actions-width: var(--measure-actions);

   /* Radius */
${block(p.radius, 'radius-')}
   --radius: var(--radius-base);

   /* Elevation - resolves against brand-layer shadow colours */
${block(p.elevation, 'elev-')}

   /* Navigation geometry */
${block(p.nav, 'nav-')}

   /* Motion */
${block(p.motion, '')}

   /* Focus ring: two-tone. The inner halo clears dark surfaces, the outer
      stroke clears light ones, so one ring passes on every background
      including the brand gradient. Both tones come from the brand layer. */
   --focus-ring: 0 0 0 2px var(--focus-halo), 0 0 0 4px var(--focus-stroke);
}

@media (prefers-reduced-motion: reduce) {
   :root { --lift-1: 0; --lift-2: 0; --lift-3: 0; }
}
`;

/* ---- L2 brand ---- */
function brandCSS(id, b) {
  const isDefault = id === 'nfccool';
  const lightSel = isDefault ? `:root, [data-brand="${id}"]` : `[data-brand="${id}"]`;
  const darkSel = isDefault
    ? `[data-theme="dark"], [data-brand="${id}"][data-theme="dark"]`
    : `[data-brand="${id}"][data-theme="dark"]`;
  return BANNER + `/* Layer 2: brand "${b.label}". Colour and typeface only.
   A second brand is a new file here, never a fork of the layers above. */

${lightSel} {
${block(b.font, 'font-')}

${block(b.light, '')}

   --brand-gradient: linear-gradient(180deg, var(--brand-blue-1) 0%, var(--brand-blue-2) 100%);
   --brand-gradient-radial: radial-gradient(at 80% 20%, var(--brand-blue-2) 0%, var(--brand-blue-1) 60%);
}

${darkSel} {
${block(b.dark, '')}

   /* The gradient collapses to the page background plus a faint accent
      radial, so brand bands blend into the page instead of forming a
      dark slab. This is nfc.cool's existing dark-mode behaviour. */
   --brand-gradient:
      radial-gradient(ellipse 85% 55% at 50% 50%, rgba(255, 199, 9, 0.10) 0%, transparent 70%),
      linear-gradient(180deg, var(--color-bg) 0%, var(--color-bg) 100%);
   --brand-gradient-radial: radial-gradient(at 50% 50%, rgba(255, 199, 9, 0.08) 0%, var(--color-bg) 60%);
}
`;
}


/* ---- Email: resolved literals. Mail clients strip custom properties and
   will not load a webfont, so email gets flat values and a system stack. ---- */
function emailCSS(b) {
  const L = b.light;
  return BANNER + `/* Layer: email. Light-mode literals only - no custom properties, no webfont.
   Generated from src/tokens.json. Inline these with a mail-safe inliner. */

.email-body { margin:0; padding:0; background:${L['color-bg']}; }
.email-wrap { width:100%; background:${L['color-bg']}; padding:32px 16px; }
.email-card { max-width:560px; margin:0 auto; background:${L['color-bg-card']};
   border:1px solid ${L['color-border']}; border-radius:14px; padding:32px; }
.email-text { font-family:-apple-system,BlinkMacSystemFont,"Segoe UI",Roboto,Helvetica,Arial,sans-serif;
   font-size:16px; line-height:1.6; color:${L['color-text-secondary']}; margin:0 0 16px; }
.email-h1 { font-family:-apple-system,BlinkMacSystemFont,"Segoe UI",Roboto,Helvetica,Arial,sans-serif;
   font-size:24px; line-height:1.2; font-weight:700; color:${L['color-text']}; margin:0 0 16px; }
.email-btn { display:inline-block; background:${L['color-link-text']}; color:${L['color-on-brand']};
   font-family:-apple-system,BlinkMacSystemFont,"Segoe UI",Roboto,Helvetica,Arial,sans-serif;
   font-size:16px; font-weight:600; text-decoration:none;
   padding:12px 24px; border-radius:10px; }
.email-link { color:${L['color-link-text']}; }
.email-muted { font-size:13px; line-height:1.5; color:${L['color-text-muted']}; }
.email-hr { border:0; border-top:1px solid ${L['color-border-light']}; margin:24px 0; }
`;
}

const outputs = [['src/tokens.css', l1]];
for (const [id, b] of Object.entries(t.brands)) outputs.push([`src/brands/${id}.css`, brandCSS(id, b)]);
outputs.push(['src/email.css', emailCSS(t.brands.nfccool)]);

let drift = false;
for (const [rel, content] of outputs) {
  const path = join(root, rel);
  if (check) {
    let cur = '';
    try { cur = readFileSync(path, 'utf8'); } catch { }
    if (cur !== content) { console.error(`DRIFT: ${rel} does not match src/tokens.json`); drift = true; }
  } else {
    writeFileSync(path, content);
    console.log(`wrote ${rel} (${content.length} bytes)`);
  }
}
if (check && !drift) console.log('no drift: generated CSS matches src/tokens.json');
process.exit(drift ? 1 : 0);
