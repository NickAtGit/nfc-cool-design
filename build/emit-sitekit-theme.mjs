/* Emits the `tokens:` block for nfc-cool-website/Theme/theme.yaml.
   That block is GENERATED OUTPUT. Never hand-edit it there.
   Usage: node build/emit-sitekit-theme.mjs > tokens-block.yaml */
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const t = JSON.parse(readFileSync(join(root, 'src/tokens.json'), 'utf8'));
const b = t.brands.nfccool, p = t.primitives;

/* SiteKit's TokenCSSGenerator only knows this fixed set of keys and maps
   camelCase -> --kebab-case. Everything else in our system ships via the
   vendored CSS files instead. */
const map = {
  colorBg: 'color-bg', colorBgAlt: 'color-bg-alt', colorBgCard: 'color-bg-card',
  colorText: 'color-text', colorTextSecondary: 'color-text-secondary', colorTextMuted: 'color-text-muted',
  colorAccent: 'color-accent', colorAccentHover: 'color-accent-hover', colorAccentLight: 'color-accent-light',
  colorBorder: 'color-border', colorBorderLight: 'color-border-light',
  colorCodeBg: 'color-code-bg', colorCodeText: 'color-code-text',
  colorShadow: 'color-shadow', colorShadowLg: 'color-shadow-lg',
};
const q = v => `"${v}"`;
let out = '# GENERATED by nfc-cool-design/build/emit-sitekit-theme.mjs. Do not hand-edit.\ntokens:\n';
for (const [camel, key] of Object.entries(map)) {
  out += `   ${camel}:${' '.repeat(Math.max(1, 19 - camel.length))}{ any: ${q(b.light[key])}, dark: ${q(b.dark[key])} }\n`;
}
out += `
   fontHeading:        { family: "Titillium Web", weights: [400, 600, 700] }
   fontBody:           { family: "Titillium Web", weights: [400, 600, 700] }
   fontMono:           { family: '${b.font.mono}' }

   maxWidth:           "${p.measure.max}"
   contentWidth:       "${p.measure.content}"
   headerHeight:       "72px"
   radius:             "${p.radius.base}"
   radiusLg:           "${p.radius.lg}"
   transition:         "${p.motion.transition}"
`;
process.stdout.write(out);
