/* Writes dist/email/: the mail layout and its pieces as Django templates, plus
   the two wordmark PNGs, for a consumer with no Node (business_card_service).
   Usage: node build/emit-email-django.mjs (part of `npm run build`).

   Nothing here is written by hand. Each template is src/email.js's own output,
   rendered with sentinel strings that are then swapped for Django blocks and
   variables, so the Django mail cannot drift from the JavaScript one: same
   tables, same inline styles, same dark overrides, same palette.

   What Django gets, and what it gives up:
   - layout.html, extended by each mail, with blocks for the title, preheader,
     heading, content and footer, and `email_asset_base` for the PNGs;
   - a header block that shows a product's own icon and name when the context
     carries `email_logo_src` (plus `email_logo_src_dark`, `email_logo_width`,
     `email_logo_height`, `email_logo_alt`, `email_brand_name`), and the
     NFC.cool wordmark otherwise;
   - one partial per block type, included with `with label=… href=…`;
   - Django's autoescape does the escaping. It does NOT validate links the way
     renderEmail does, and it writes no plain-text part: a Django mail keeps
     its own .txt template, as it already does for subjects. */
import { mkdirSync, writeFileSync, copyFileSync } from 'node:fs';
import { join } from 'node:path';
import { root } from './guideline.mjs';
import { renderEmail, renderBlock, EMAIL_ASSETS } from '../src/email.js';
import { palette } from '../src/email/palette.js';

const out = join(root, 'dist/email');
const tpl = join(out, 'django');
mkdirSync(tpl, { recursive: true });

const S = k => `ZZ${k}ZZ`;
const URL_ = k => `https://zz.invalid/${S(k)}`;
const BANNER = '{% comment %}GENERATED by build/emit-email-django.mjs from src/email.js. Do not edit; rebuild the design package.{% endcomment %}';

function swap(html, pairs) {
  for (const [from, to] of pairs) {
    if (!html.includes(from)) throw new Error(`sentinel ${from} not found: src/email.js changed shape, update this generator`);
    html = html.replaceAll(from, to);
  }
  return html;
}

/* ---- the layout ---- */
let { html } = renderEmail({
  title: S('TITLE'), heading: S('HEADING'), preheader: S('PREHEADER'),
  assetBaseUrl: `${URL_('ASSETS')}/`,
  blocks: [{ type: 'text', text: S('CONTENT') }],
  footer: { product: S('PRODUCT'), reason: S('REASON'), links: [{ label: S('LINKS'), href: URL_('LINK') }] },
});
const contentRow = new RegExp(`<tr><td[^>]*><p class="em-t"[^>]*>${S('CONTENT')}</p></td></tr>`);
if (!contentRow.test(html)) throw new Error('content row not found: src/email.js changed shape, update this generator');
html = html.replace(contentRow, '{% block content %}{% endblock %}');
const linkAnchor = new RegExp(`<a class="em-m" href="${URL_('LINK')}" style="([^"]*)">${S('LINKS')}</a>`);
const linkStyle = linkAnchor.exec(html)?.[1];
if (!linkStyle) throw new Error('footer link not found: src/email.js changed shape, update this generator');
html = html.replace(linkAnchor, '{% block footer_links %}{% endblock %}');
html = swap(html, [
  [`<title>${S('TITLE')}</title>`, '<title>{% block title %}{{ email_title }}{% endblock %}</title>'],
  [`aria-label="${S('TITLE')}"`, 'aria-label="{{ email_title }}"'],
  [S('PREHEADER'), '{% block preheader %}{% endblock %}'],
  [S('HEADING'), '{% block heading %}{% endblock %}'],
  [`${URL_('ASSETS')}/`, '{{ email_asset_base }}'],
  [S('PRODUCT'), `{% block footer_product %}${palette.label}{% endblock %}`],
  [S('REASON'), '{% block footer_reason %}{% endblock %}'],
]);
/* ---- the header: a product logo when the context has one, else the wordmark ---- */
const HEAD_START = '<tr><td align="left" style="padding-bottom:28px">';
const headerRow = mail => {
  const a = mail.indexOf(HEAD_START);
  const b = mail.indexOf('\n<tr><td><h1', a);
  if (a < 0 || b < 0) throw new Error('header row not found: src/email.js changed shape, update this generator');
  return mail.slice(a, b);
};
const LOGO_W = 587, LOGO_H = 593;
let logoRow = headerRow(renderEmail({
  heading: 'x', blocks: [],
  brand: { name: S('NAME'), logo: { src: URL_('LOGO'), srcDark: URL_('LOGODARK'), width: LOGO_W, height: LOGO_H, alt: S('ALT') } },
}).html);
const darkPart = /<!--\[if !mso\]><!--><div class="em-wm-dark"[\s\S]*?<\/div><!--<!\[endif\]-->/;
const nameCell = /<td class="em-brand-name"[\s\S]*?<\/td>/;
if (!darkPart.test(logoRow) || !nameCell.test(logoRow)) throw new Error('logo header pieces not found: src/email.js changed shape, update this generator');
logoRow = logoRow
  .replace(darkPart, m => `{% if email_logo_src_dark %}${m}{% endif %}`)
  .replace(nameCell, m => `{% if email_brand_name %}${m}{% endif %}`);
logoRow = swap(logoRow, [
  ['class="em-logo em-wm-light em-h"', 'class="em-logo{% if email_logo_src_dark %} em-wm-light{% endif %} em-h"'],
  [URL_('LOGODARK'), '{{ email_logo_src_dark }}'],
  [URL_('LOGO'), '{{ email_logo_src }}'],
  [`width="${LOGO_W}"`, 'width="{{ email_logo_width }}"'],
  [`width:${LOGO_W}px`, 'width:{{ email_logo_width }}px'],
  [`height="${LOGO_H}"`, 'height="{{ email_logo_height }}"'],
  [`height:${LOGO_H}px`, 'height:{{ email_logo_height }}px'],
  [`border-radius:${Math.round(LOGO_W * 0.22)}px`, 'border-radius:{% widthratio email_logo_width 100 22 %}px'],
  [S('ALT'), '{{ email_logo_alt|default:"" }}'],
  [S('NAME'), '{{ email_brand_name }}'],
]);
const wordmarkRow = headerRow(html);
html = html.replace(wordmarkRow, `{% block header %}{% if email_logo_src %}${logoRow}{% else %}${wordmarkRow}{% endif %}{% endblock %}`);

const files = { 'layout.html': `${BANNER}\n${html}` };

/* ---- one partial per block ---- */
const row = (inner, gap) => `<tr><td align="left" style="padding-top:{{ gap|default:"${gap}" }}px">${inner}</td></tr>\n`;
const PARTIALS = {
  'text.html':          [{ type: 'text', text: S('TEXT') }, [[S('TEXT'), '{{ text }}']], 16],
  'note.html':          [{ type: 'note', text: S('TEXT') }, [[S('TEXT'), '{{ text }}']], 20],
  'quote.html':         [{ type: 'quote', text: S('TEXT') }, [[S('TEXT'), '{{ text }}']], 20],
  'button.html':        [{ type: 'button', label: S('LABEL'), href: URL_('HREF') }, [[S('LABEL'), '{{ label }}'], [URL_('HREF'), '{{ href }}']], 28],
  'link_fallback.html': [{ type: 'link-fallback', label: S('LABEL'), href: URL_('HREF') }, [[S('LABEL'), '{{ label|default:"Or copy this link:" }}'], [URL_('HREF'), '{{ href }}']], 20],
  'divider.html':       [{ type: 'divider' }, [], 28],
};
for (const [name, [block, pairs, gap]] of Object.entries(PARTIALS)) {
  files[name] = `${BANNER}\n${row(swap(renderBlock(block), pairs), gap)}`;
}
files['footer_link.html'] = `${BANNER}\n<a class="em-m" href="{{ href }}" style="${linkStyle}">{{ label }}</a>`;

for (const [name, body] of Object.entries(files)) writeFileSync(join(tpl, name), body);
for (const f of EMAIL_ASSETS) copyFileSync(join(root, 'src/email', f), join(out, f));
console.log(`wrote dist/email/django/ (${Object.keys(files).length} templates) and ${EMAIL_ASSETS.length} PNGs`);
